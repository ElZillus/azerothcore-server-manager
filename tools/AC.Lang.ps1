# =====================================================================
#  AC.Lang.ps1 - Sprachtabelle / language table (de, en)
#  Zugriff ueber:  T 'key'   bzw.  T 'key' @(arg1, arg2)
#  Platzhalter in den Texten sind {0}, {1}, ...
# =====================================================================

$script:AcLangVersion = '2026-09-06.98'

$script:AcLanguage = 'en'
$script:AcLanguages = @{ de = 'Deutsch'; en = 'English' }

function Set-AcLanguage {
    param([string]$Code)
    if ($script:AcStrings.ContainsKey($Code)) { $script:AcLanguage = $Code } else { $script:AcLanguage = 'en' }
}

function T {
    # $Values fuellt die Platzhalter {0}, {1}, ... ("Args" waere eine PowerShell-Automatikvariable)
    param([Parameter(Mandatory)][string]$Key, [object[]]$Values = @())
    $table = $script:AcStrings[$script:AcLanguage]
    $text = $null
    if ($table -and $table.ContainsKey($Key)) { $text = $table[$Key] }
    if (-not $text -and $script:AcStrings['en'].ContainsKey($Key)) { $text = $script:AcStrings['en'][$Key] }
    if (-not $text) { return $Key }
    if ($Values -and $Values.Count -gt 0) { return ([string]::Format($text, $Values)) }
    return $text
}

